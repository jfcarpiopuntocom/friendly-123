'use strict';
const {test}=require('node:test'), assert=require('node:assert/strict'), fs=require('node:fs'), vm=require('node:vm');
const src=fs.readFileSync('src/app/app-inline-03.js','utf8');
const code=src.slice(src.indexOf('(function actualizacionSola()'),src.indexOf('// Microcirugia 5',src.indexOf('(function actualizacionSola()')));
test('PIN adopts once when controllerchange precedes activation, without polling',async()=>{
  let reloads=0;
  const local=new Map([['f123_version_vista','1.0|new']]), session=new Map([['f123_act_sola_pendiente','1']]);
  const st=m=>({getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k)});
  const handlers={};
  const sw={controller:{state:'activated'},addEventListener:(k,fn)=>(handlers[k]??=[]).push(fn),removeEventListener:(k,fn)=>handlers[k]=(handlers[k]??[]).filter(x=>x!==fn)};
  const gate={style:{display:'block'},getClientRects:()=>[{}]};
  const document={visibilityState:'visible',getElementById:id=>id==='oc-gate'?gate:null,querySelectorAll:()=>[],addEventListener(){},body:{appendChild(){}},createElement:()=>({style:{},setAttribute(){},remove(){},innerHTML:''})};
  const window={addEventListener(){},requestAnimationFrame:fn=>fn()};
  const next={state:'activating',listeners:[],addEventListener(k,fn){assert.equal(k,'statechange');this.listeners.push(fn)},removeEventListener(k,fn){this.listeners=this.listeners.filter(x=>x!==fn)},postMessage(){for(const fn of [...handlers.message??[]])fn({source:this,data:{tipo:'shell-actual',shell:'new'}})}};
  vm.runInNewContext(code,{window,navigator:{serviceWorker:sw},document,localStorage:st(local),sessionStorage:st(session),getComputedStyle:()=>({display:'block'}),fetch:async()=>({ok:true,json:async()=>({version:'1.0',shell:'new'})}),setTimeout:()=>1,clearTimeout(){},setInterval(){},location:{reload(){reloads++}},_ocActSolaOn:true,_recargarSeguroVersion(){}});
  const flush=async()=>{for(let i=0;i<30;i++)await Promise.resolve()};
  sw.controller=next;
  for(const fn of handlers.controllerchange)fn();
  await flush();
  assert.equal(reloads,0,'never reload while activating');
  next.state='activated';
  for(const fn of [...next.listeners])fn();
  for(const fn of [...handlers.message??[]])fn({source:next,data:{tipo:'shell-actualizado',shell:'new'}});
  await flush();
  assert.equal(reloads,1,'activation must trigger pending adoption without 15-second polling');
  assert.equal(session.has('f123_act_sola_pendiente'),false);
  for(const fn of handlers.controllerchange)fn();
  await flush();
  assert.equal(reloads,1,'no second reload');
});
