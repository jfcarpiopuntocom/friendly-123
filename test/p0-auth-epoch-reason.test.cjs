'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../docs/tab-session.js'),'utf8');
const start=src.indexOf(' function epoch(reason){');
const end=src.indexOf(' function clearPanel()',start);
assert(start>=0&&end>start,'epoch diagnostic helper exists');
assert.match(src,/epoch\('pin-claim'\)/);
assert.match(src,/epoch\('logout'\)/);
const store=new Map();
const ctx={window:{OC_AUTH_SESSION_EPOCH:4},localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},document:{hidden:true},pending:false,claimed:true,Date,JSON};
vm.createContext(ctx);vm.runInContext(src.slice(start,end),ctx);
vm.runInContext("epoch('pin-claim');epoch('logout')",ctx);
assert.equal(ctx.window.OC_AUTH_SESSION_EPOCH,6,'epoch fencing remains active');
const trace=JSON.parse(store.get('f123_p0_auth_epoch_trace_v1'));
assert.deepEqual(trace.map(x=>x.reason),['pin-claim','logout']);
assert.equal(trace[0].hidden,true);
assert.equal(JSON.stringify(trace).includes('license'),false);
console.log('P0 epoch reason trace: PASS');
