  const LS_KEY = "f123_lang"; // f123_ prefijo (2026-07-17): namespace propio, no compartir con AMIGABLE
  let lang = localStorage.getItem(LS_KEY);
  if (lang !== "en" && lang !== "es") lang = "en"; // default English

  function t(key, fallback) {
    const d = DICT[lang] || DICT.en;
    if (d[key] != null) return d[key];
    if (DICT.en[key] != null) return DICT.en[key];
    return fallback != null ? fallback : key;
  }

  function getLang() { return lang; }

  // Locale para Intl/toLocaleString derivado del idioma ACTIVO de la app, no
  // fijo a Ecuador — así "mié, 15 jul" se vuelve "Wed, Jul 15" al cambiar a
  // inglés, y viceversa. "es-US" (no "es-EC"): el español aquí es para
  // personal/dueños hispanohablantes en EEUU, no formato de Ecuador.
  function locale() { return lang === "en" ? "en-US" : "es-US"; }

  // tf("hoy.subOwner", {monto:"$5.00", n:3}) -> interpola {monto}/{n} en el texto.
  function tf(key, vars) {
    let s = t(key);
    if (vars) Object.keys(vars).forEach((k) => { s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]); });
    return s;
  }

  function setLang(l) {
    lang = l === "es" ? "es" : "en";
    try { localStorage.setItem(LS_KEY, lang); } catch (_) {}
    document.documentElement.lang = lang;
    applyStatic();
    // Las vistas dinámicas escuchan esto para re-renderizar en el nuevo idioma.
    window.dispatchEvent(new CustomEvent("oc-lang-change", { detail: { lang } }));
  }

  // Traduce nodos estáticos marcados en el HTML.
  //   data-i18n="clave"          -> textContent
  //   data-i18n-html="clave"     -> innerHTML (para textos con marcado)
  //   data-i18n-attr="attr:clave,attr:clave" -> atributos (title, placeholder...)
  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    // 2026-08-19, aprobado JFC: si el <title> lleva data-i18n el textContent
    // ya se actualiza arriba, pero el tab del navegador solo se refresca
    // confiablemente si tambien reasignamos document.title. Sin esto, cambiar
    // el idioma dejaba el tab con el nombre viejo hasta el proximo evento.
    if (!root) {
      const titleEl = document.querySelector("title[data-i18n]");
      if (titleEl && titleEl.textContent && document.title !== titleEl.textContent) {
        document.title = titleEl.textContent;
      }
    }
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      el.getAttribute("data-i18n-attr").split(",").forEach((pair) => {
        const idx = pair.indexOf(":");
        if (idx > 0) {
          const attr = pair.slice(0, idx).trim();
          const key = pair.slice(idx + 1).trim();
          if (attr && key) el.setAttribute(attr, t(key));
        }
      });
    });
  }

  window.OCI18n = { t, tf, setLang, getLang, locale, applyStatic, DICT };
  window.t = t; // atajo para las plantillas de las vistas dinámicas
  window.tf = tf;

  document.addEventListener("DOMContentLoaded", () => {
    document.documentElement.lang = lang;
    applyStatic();
  });
